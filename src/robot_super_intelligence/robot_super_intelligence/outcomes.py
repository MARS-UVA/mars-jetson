"""Named return conditions shared by states and the action server."""

from enum import Enum


class Outcome(str, Enum):
    START_SUCCESS = 'START_SUCCESS'
    CONSTRUCTION_REACHED = 'CONSTRUCTION_REACHED'
    DUMP_SUCCESS = 'DUMP_SUCCESS'
    EXCAVATION_REACHED = 'EXCAVATION_REACHED'
    EXCAVATE_SUCCESS = 'EXCAVATE_SUCCESS'
    RUN_END = 'RUN_END'
    NOT_IMPLEMENTED = 'NOT_IMPLEMENTED'
    FAILED = 'FAILED'
    TIME_LIMIT_REACHED = 'TIME_LIMIT_REACHED'
    CANCELED = 'CANCELED'
    MODE_EXITED = 'MODE_EXITED'
    SHUTDOWN = 'SHUTDOWN'
    ESTOP = 'ESTOP'
